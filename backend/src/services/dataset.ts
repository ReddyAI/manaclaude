import type { FinanceDataset } from '@manaclaude/shared';
import { selectAll } from '../db/table';
import {
  activitiesTable,
  balanceSnapshotsTable,
  budgetsTable,
  categoriesTable,
  categoryGroupsTable,
  connectionsTable,
  fxRatesTable,
  goalsTable,
  holdingsTable,
  merchantsTable,
  pricesTable,
  receiptsTable,
  recurringTable,
  rulesTable,
  securitiesTable,
  tagsTable,
  taxLotsTable,
  transactionsTable,
  transferLinksTable,
} from '../db/tables';
import { getSettings } from './settings';
import { listAccounts } from './accounts';

/** The whole dataset in the shape the app already renders (GET /v1/dataset). */
export async function loadDataset(db: D1Database): Promise<FinanceDataset> {
  const [
    accounts,
    balanceHistory,
    transactions,
    transferLinks,
    categoryGroups,
    categories,
    tags,
    merchants,
    rules,
    budgets,
    goals,
    recurring,
    securities,
    holdings,
    taxLots,
    activities,
    prices,
    receipts,
    fxRates,
    connections,
    slots,
    settings,
  ] = await Promise.all([
    listAccounts(db),
    selectAll(db, balanceSnapshotsTable, '', [], 'date'),
    selectAll(db, transactionsTable, '', [], 'date DESC, created_at DESC'),
    selectAll(db, transferLinksTable),
    selectAll(db, categoryGroupsTable, '', [], '"order"'),
    selectAll(db, categoriesTable, '', [], '"order"'),
    selectAll(db, tagsTable),
    selectAll(db, merchantsTable),
    selectAll(db, rulesTable, '', [], 'priority'),
    selectAll(db, budgetsTable),
    selectAll(db, goalsTable),
    selectAll(db, recurringTable),
    selectAll(db, securitiesTable),
    selectAll(db, holdingsTable),
    selectAll(db, taxLotsTable),
    selectAll(db, activitiesTable, '', [], 'date'),
    selectAll(db, pricesTable, '', [], 'date'),
    selectAll(db, receiptsTable),
    selectAll(db, fxRatesTable, '', [], 'date'),
    selectAll(db, connectionsTable),
    db.prepare('SELECT connector_id, used FROM connector_slots').all<{
      connector_id: string;
      used: number;
    }>(),
    getSettings(db),
  ]);
  return {
    accounts,
    balanceHistory,
    transactions,
    transferLinks,
    categoryGroups,
    categories,
    tags,
    merchants,
    rules,
    budgets,
    goals,
    recurring,
    securities,
    holdings,
    taxLots,
    activities,
    prices,
    receipts,
    fxRates,
    connections,
    connectorSlotsUsed: Object.fromEntries(slots.results.map((s) => [s.connector_id, s.used])),
    settings,
  };
}
